    business_line varchar(40) not null,
    revenue_wan numeric(14,2) not null,
    cost_wan numeric(14,2) not null,
    selling_expense_wan numeric(14,2) not null,
    admin_expense_wan numeric(14,2) not null,
    r_and_d_wan numeric(14,2) not null,
    receivables_wan numeric(14,2) not null,
    inventory_wan numeric(14,2) not null,
    operating_cash_flow_wan numeric(14,2) not null,
    order_backlog_wan numeric(14,2) not null,
    primary key (period, business_line)
);

